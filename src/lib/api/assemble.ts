function mergePaths(
  ...pathObjects: Array<Record<string, unknown>>
): Record<string, unknown> {
  const merged: Record<string, unknown> = {};
  for (const obj of pathObjects) {
    for (const [key, value] of Object.entries(obj)) {
      if (merged[key]) {
        Object.assign(merged[key], value);
      } else {
        merged[key] = value;
      }
    }
  }
  return merged;
}

